from django.test import TestCase
from rest_framework.test import APIClient
from rest_framework import status
from apps.products.models import Category


class CategoryModelAndAPITest(TestCase):
    def setUp(self):
        self.client = APIClient()
        self.parent_cat = Category.objects.create(
            name='Men',
            description='Men fashion'
        )
        self.child_cat = Category.objects.create(
            name='Agbada',
            parent=self.parent_cat,
            description='Grand Agbada sets'
        )

    def test_category_slug_autogenerated(self):
        self.assertEqual(self.parent_cat.slug, 'men')
        self.assertEqual(self.child_cat.slug, 'agbada')

    def test_unique_slug_conflict_resolution(self):
        cat_duplicate = Category.objects.create(name='Men Apparel', slug='men')
        self.assertEqual(cat_duplicate.slug, 'men-1')

    def test_category_list_api(self):
        response = self.client.get('/api/v1/categories/')
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.assertTrue(response.data['success'])
        self.assertEqual(len(response.data['categories']), 1)
        parent_data = response.data['categories'][0]
        self.assertEqual(parent_data['name'], 'Men')
        self.assertEqual(len(parent_data['children']), 1)
        self.assertEqual(parent_data['children'][0]['name'], 'Agbada')

    def test_category_detail_api(self):
        response = self.client.get(f'/api/v1/categories/{self.child_cat.slug}/')
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.assertTrue(response.data['success'])
        self.assertEqual(response.data['category']['name'], 'Agbada')
